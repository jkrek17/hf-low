#!/usr/bin/env python3
"""Build docs/data/era5-compare.js: the P(HF) model set against the OPC-analysed storms.

    python3 tools/build_era5_compare.py \
        --matches matches.csv --probs-2004 fix_probs_2004.csv.gz \
        --residual residual_unlisted_both_rules_2004.csv \
        --source "research/era5/gust_depth/results/matches.csv and hf_probability_tracks/results at <commit>"

Inputs: the archive-to-track matches (research/era5/gust_depth/results/matches.csv, PR 52 rule: pipeline A
track within 500 km of the archive peak), the per-fix P tables of research/era5/hf_probability_tracks
(also in the project folder hf-probability-tracks/), and the archive itself (docs/data/hf-lows.json).
P is model N (no gust predictor), leave-one-season-out. It is a PROXY model output: the label is
pipeline A's gust index at 71.7 kt in ERA5, not an observation. 2004-05 to 2025-26 only.

Wire format (append-only):
  HF_ERA5_CMP.opc[i] = [key, track, pAll, pPre, leadH]
    key    archive id as basin:id (the matches key)
    track  pipeline A track id, -1 when no track lies within 500 km
    pAll   peak P*10000 over the track's scored 00/12 UTC fixes; -1 when no track or no scored fix
    pPre   peak P*10000 over scored fixes at or before the first archive HF fix; -1 when none
    leadH  hours from the first scored fix with P >= 0.5 to the first archive HF fix, on fixes at or
           before it; -1 when P never reached 0.5 by then. Fixes are 12 hourly, so steps of 12.
  HF_ERA5_CMP.unl[i] = [track, basin(0 atl,1 pac), season, peak time YYYYMMDDHH, lat*4, lon*4,
                        min pressure hPa*10, gust kt*10, peak pre-HF P*10000, margin over 71.7 kt *10]
"""
import argparse
import gzip
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CUT = 0.5


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--matches", required=True)
    ap.add_argument("--probs-2004", required=True)
    ap.add_argument("--residual", required=True)
    ap.add_argument("--source", required=True)
    ap.add_argument("--archive", default=os.path.join(ROOT, "docs", "data", "hf-lows.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "data", "era5-compare.js"))
    a = ap.parse_args()

    arch = json.load(open(a.archive))
    lf, ff = arch["lowFields"], arch["fixFields"]
    onset = {}
    for r in arch["lows"]:
        e = dict(zip(lf, r))
        hf = [f[0] for f in e["fixes"] if f[3] == "HF"]
        onset[e["basin"] + ":" + e["id"]] = min(hf) if hf else None

    m = pd.read_csv(a.matches)
    m = m[m.peak == "HF"].copy()
    fx = pd.read_csv(a.probs_2004, dtype={"time": str})
    fx["t"] = pd.to_datetime(fx.time, format="%Y%m%d%H")
    by = {t: g.sort_values("t") for t, g in fx.groupby("track")}

    opc = []
    for _, r in m.iterrows():
        o = onset.get(r.key)
        tr = int(r.track) if pd.notna(r.track) else -1
        pAll = pPre = lead = -1
        g = by.get(tr)
        if g is not None and len(g):
            pAll = int(round(g.P_N.max() * 10000))
            if o:
                t0 = pd.to_datetime(str(o), format="%Y%m%d%H")
                pre = g[g.t <= t0]
                if len(pre):
                    pPre = int(round(pre.P_N.max() * 10000))
                    hit = pre[pre.P_N >= CUT]
                    if len(hit):
                        lead = int((t0 - hit.t.min()).total_seconds() // 3600)
        opc.append([r.key, tr, pAll, pPre, lead])
    opc.sort(key=lambda x: x[0])

    res = pd.read_csv(a.residual)
    unl = []
    for _, r in res.sort_values("peak_time").iterrows():
        unl.append([int(r.track), 0 if r.basin == "atl" else 1, int(r.season), int(r.peak_time),
                    int(round(r.peak_lat * 4)), int(round(((r.peak_lon + 180) % 360 - 180) * 4)),
                    int(round(r.minp * 10)), int(round(r.gust800_kt * 10)),
                    int(round(r.Ppre_N * 10000)), int(round(r.margin * 10))])

    meta = {"what": "ERA5 proxy P(HF within 24 h), model N (no gust predictor), leave-one-season-out, set against the "
                    "OPC-analysed hurricane-force storms of 2004-05 to 2025-26. Pipeline A label, not the archive; "
                    "a model output, not an observation.",
            "source": a.source, "cut": CUT, "opc": len(opc), "unlisted": len(unl),
            "fields": {"opc": ["key", "track", "pAll*10000", "pPre*10000", "leadH"],
                       "unl": ["track", "basin(0 atl,1 pac)", "season", "peakTime", "lat*4", "lon*4",
                               "minp*10", "gust*10", "pPre*10000", "margin*10"]}}
    with open(a.out, "w") as f:
        f.write("/* generated by tools/build_era5_compare.py - do not edit. ERA5 PROXY model output, not an observation. */\n")
        f.write("window.HF_ERA5_CMP = " + json.dumps({"meta": meta, "opc": opc, "unl": unl}, separators=(",", ":")) + ";\n")
    print(len(opc), "OPC events,", sum(1 for x in opc if x[1] < 0), "without a track,", len(unl), "unlisted high-P")


if __name__ == "__main__":
    main()
