#!/usr/bin/env python3
"""Build docs/data/era5-probtable.js: how the P(HF) bands turned out.

    python3 tools/build_era5_probtable.py \
        --probs-2004 fix_probs_2004.csv.gz --probs-pre fix_probs_pre2004.csv.gz \
        --source "research/era5/hf_probability_tracks/results at <commit>"

Inputs are the per-fix tables of research/era5/hf_probability_tracks, the same
ones tools/build_era5_allprob.py reads. P is model N (no gust predictor),
leave-one-season-out for 2004-05 onward. Everything is ERA5 PROXY, pipeline A:
the label hf24 is the gust index reaching 71.7 kt within 24 h, not the archive.

Output window.HF_ERA5_PROBTABLE (append-only):
  bands   [lo, hi) edges of the five P bands, as fractions
  seasons first and last season start year of the 2004-2025 sample
  b.all / b.atl / b.pac:
    fix   per band [n fixes, n fixes followed by HF within 24 h, mean P]
    storm per band [n lows whose highest P fell in the band, n of them that
          reached HF at some fix]
    pre   per band [n fixes of catalog events, n fixes of matched null cases]
          (1979-2003 sample is enriched in events: shares, never rates)
"""
import argparse
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EDGES = [0, 0.05, 0.2, 0.5, 0.8, 1.0001]


def band(p):
    return np.clip(np.digitize(p, EDGES[1:-1]), 0, 4)


def one(a, b, basin):
    if basin != "all":
        a, b = a[a.basin == basin], b[b.basin == basin]
    a = a.assign(band=band(a.P_N.to_numpy()), hf=a.hf24.astype(int))
    fix = []
    for k in range(5):
        g = a[a.band == k]
        fix.append([int(len(g)), int(g.hf.sum()), round(float(g.P_N.mean()), 4) if len(g) else 0])
    s = a.groupby("track").agg(mx=("P_N", "max"), ever=("hf", "max"))
    s["band"] = band(s.mx.to_numpy())
    storm = [[int((s.band == k).sum()), int(s.ever[s.band == k].sum())] for k in range(5)]
    b = b.assign(band=band(b.P_N.to_numpy()))
    pre = [[int(((b.band == k) & (b.role == "event")).sum()), int(((b.band == k) & (b.role == "null_case")).sum())] for k in range(5)]
    return {"fix": fix, "storm": storm, "pre": pre}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--probs-2004", required=True)
    ap.add_argument("--probs-pre", required=True)
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "data", "era5-probtable.js"))
    x = ap.parse_args()
    a, b = pd.read_csv(x.probs_2004), pd.read_csv(x.probs_pre)
    out = {
        "meta": {"what": "How the ERA5 proxy P(HF within 24 h) bands turned out (model N, leave-one-season-out, 2004-2025), and the 1979-2003 catalog events against their matched null cases. Pipeline A label (gust index at 71.7 kt), not the archive; a model output, not an observation.",
                 "source": x.source, "fixes_2004": int(len(a)), "lows_2004": int(a.track.nunique()),
                 "fixes_pre": int(len(b)), "lows_pre": int(b.track.nunique())},
        "bands": EDGES[:-1] + [1.0],
        "seasons": [int(a.season.min()), int(a.season.max())],
        "b": {k: one(a, b, k) for k in ("all", "atl", "pac")},
    }
    with open(x.out, "w") as f:
        f.write("/* generated by tools/build_era5_probtable.py - do not edit. ERA5 PROXY model output, not an observation. */\n")
        f.write("window.HF_ERA5_PROBTABLE = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(x.out, os.path.getsize(x.out), "bytes")


if __name__ == "__main__":
    main()
