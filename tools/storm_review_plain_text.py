#!/usr/bin/env python3
"""Apply the plain-language wording to the committed storm review pages (text only).

usage: storm_review_plain_text.py DOCS_DIR

The pages are generated by storm_review_v2.py from ERA5 extractions that are not kept (about 1.1 GB a storm), so the wording
change was applied to the committed HTML directly, with the same replacements made in the generator's templates. Figures, numbers
and facts are untouched; only sentences, labels and units around them change. Idempotent: a page already in the new wording is left alone.
"""
import glob, os, re, sys

NOTE = ('<div class="note"><strong>ERA5 proxy, not direct observation.</strong> ERA5 is a weather model re-run over past years and blended with the observations '
        'available. Tracks are the project&rsquo;s pipeline A tracks, found in ERA5 itself. The gust index is the strongest ERA5 10 m gust over the ocean within 800 km '
        '(about 430 nm) of the low, a stand-in (proxy) for the sustained wind OPC warns on. Structure and upper-level numbers are ERA5 at 1.5&deg;; maps and the wind field are ERA5 at 0.25&deg;. '
        'Distances are nautical miles.</div>')
STRUCT_HELP = ('<p class="muted">How to read the structure numbers. Hart&rsquo;s B says how lopsided the low is: above about 10 m it is frontal, near zero it is symmetric. '
               'The lower-level core number says whether the 900 to 600 hPa layer is cold (negative) or warm (positive). A frontal low with a cold core is the early stage; '
               'a warm seclusion has warm air wrapped around the centre. The classes come from a coarse 1.5&deg; grid, so treat them as a guide.</p>')
LABELS = [
    ("highest 250 hPa wind within 1,000 km", "strongest 250 hPa wind (the jet) within 540 nm"),
    ("300 hPa divergence within 500 km", "upper-level divergence (300 hPa) within 270 nm"),
    ("500 hPa vorticity advection within 500 km", "vorticity advection (500 hPa) within 270 nm"),
    ("Eady growth rate (850-500 hPa)", "Eady growth rate, the support for storm growth (850&ndash;500 hPa)"),
    ("column water vapour within 500 km", "moisture in the air column within 270 nm"),
    ("largest SST gradient within 500 km", "sharpest sea-surface temperature gradient within 270 nm"),
]
UNITS = [(" 1e-5 /s<", " &times;10<sup>&minus;5</sup> /s<"), (" 1e-9 /s2<", " &times;10<sup>&minus;9</sup> /s&sup2;<"), (" kg/m2<", " kg/m&sup2;<")]


def sub1(pat, rep, s, flags=0):
    return re.sub(pat, rep, s, count=1, flags=flags)


def convert_page(s):
    if "How to read the structure numbers" in s:
        return s
    s = sub1(r'<div class="note">.*?</div>', lambda m: NOTE, s, re.S)
    # section 3: structure sentence
    s = re.sub(r"\(Hart B (-?\d+) m, lower-level core ([-+]?\d+) m\)", lambda m: f"(Hart B {m[1].replace('-', '&minus;')} m, lower-level core {m[2].replace('-', '&minus;')} m)", s)
    s = re.sub(r"\(B (-?\d+) m, ([-+]?\d+) m\)", lambda m: f"(B {m[1].replace('-', '&minus;')} m, lower-level core {m[2].replace('-', '&minus;')} m)", s)
    s = s.replace("in these 1.5&deg; diagnostics. </p>", "in these 1.5&deg; diagnostics. </p>" + STRUCT_HELP, 1) if "never reached" in s else \
        re.sub(r"(<section><div class=\"tag\">3\. How it developed</div>\n<p>.*?</p>)", lambda m: m[1] + STRUCT_HELP, s, count=1, flags=re.S)
    s = s.replace("the fall over the previous 24 h against the latitude-scaled bomb yardstick; the gust index; the ocean area at 71.7 kt or more; the 250 hPa jet; the two upper-level lift terms; and Hart&rsquo;s two structure parameters with the structure class along the bottom.",
                  "the fall in pressure over the previous 24 h against the bomb yardstick (scaled by latitude); the gust index; the ocean area with gusts of 71.7 kt or more; the 250 hPa jet; the two upper-level lift terms (divergence and vorticity advection); and two structure measures (frontal against symmetric, cold core against warm core) with the structure class along the bottom.")
    # section 4: forcing sentence
    def forcing(m):
        return (f"During its fastest 24 h fall ({m[1]}) the strongest 250 hPa wind within about 540 nm averaged <b>{m[2]} kt</b>. "
                f"Upper-level divergence at 300 hPa over the centre averaged {m[3].replace('-', '&minus;')} &times;10<sup>&minus;5</sup>/s (positive means air spreading out aloft, which draws air up from below), "
                f"and 500 hPa vorticity advection {m[4].replace('-', '&minus;')} &times;10<sup>&minus;9</sup>/s&sup2; (positive means cyclonic spin arriving aloft). "
                f"The Eady growth rate (850&ndash;500 hPa), a measure of how favourable the temperature contrast and wind shear are for the storm to grow, averaged {m[5]} per day, "
                f"and the moisture in the air column within about 270 nm averaged {m[6]} kg/m&sup2;.")
    s = re.sub(r"During its fastest 24 h fall \(([^)]*)\) the highest 250 hPa wind within 1,000 km averaged <b>(\d+) kt</b>, "
               r"300 hPa divergence over the centre averaged ([-+]?[\d.]+) \(units 1e-5 /s; positive = air being drawn up\) and "
               r"500 hPa vorticity advection ([-+]?[\d.]+) \(1e-9 /s&sup2;; positive = cyclonic spin arriving aloft\)\. "
               r"The 850-500 hPa Eady growth rate, a measure of baroclinic \(temperature-contrast\) support, averaged ([\d.]+) per day, "
               r"and column water vapour within 500 km averaged (\d+) kg/m&sup2;\.", forcing, s)
    # section 6 caption
    s = s.replace("Left: the storm&rsquo;s path through Hart&rsquo;s cyclone phase space.", "Left: the storm&rsquo;s path through Hart&rsquo;s cyclone phase space, a diagram of how lopsided the low is against how warm its core is.")
    # section 7
    s = s.replace('7. How its set-up compares with other hurricane-force-strength lows', '7. Was its set-up unusual? Compared with other hurricane-force-strength lows')
    s = re.sub(r"Median over this storm&rsquo;s (\d+) fixes with a gust index of 71\.7 kt or more, placed among all such fixes in the same basin since 2004&ndash;05 \(pipeline A, ERA5 proxy; fixes from one storm are not independent, so read it as a rough rank, not a test\)\.",
               r"For this storm&rsquo;s \1 fixes with a gust index of 71.7 kt or more, the table gives the median of each ingredient and how it ranks among all such fixes in the same basin since 2004&ndash;05 (pipeline A, ERA5 proxy). Fixes from one storm are not independent, so read the rank as a rough guide, not a test.", s)
    for a, b in LABELS:
        s = s.replace(f"<td>{a}</td>", f"<td>{b}</td>")
    for a, b in UNITS:
        s = s.replace(a, b)
    s = re.sub(r"above (\d+)% of them", r"higher than \1% of them", s)
    s = s.replace("<th class=\"num\">Compared with HF-strength fixes</th>", "<th class=\"num\">Higher than this share of HF-strength fixes</th>")
    # read with care
    s = s.replace("The Hart terms use 900, 850, 700, 600, 500, 400 and 300 hPa heights on a 1.5&deg; grid, not the original 50 hPa spacing, so read the structure class as a guide, not a classification to the metre.",
                  "The structure measures (Hart&rsquo;s cyclone phase space) use seven pressure levels on a 1.5&deg; grid, coarser than the original method, so read the structure class as a guide, not an exact classification.")
    s = s.replace("A storm is one case: nothing here is a trend or a forecast rule.", "A storm is one case: nothing here is a trend or a forecast rule.")
    return s


if __name__ == "__main__":
    d = sys.argv[1]
    for p in sorted(glob.glob(os.path.join(d, "storm-review-*.html"))):
        if os.path.basename(p) == "storm-reviews.html":
            continue
        s = open(p).read(); t = convert_page(s)
        if t != s:
            open(p, "w").write(t)
    print("done")
